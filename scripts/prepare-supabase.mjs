import { readdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../supabase/', import.meta.url);
const names = (await readdir(new URL('migrations/', root)))
  .filter(name => name.endsWith('.sql'))
  .sort();
const bodies = [];

for (const name of names) {
  const sql = (await readFile(new URL('migrations/' + name, root), 'utf8')).trim();
  if (!/^begin;/i.test(sql) || !/commit;$/i.test(sql)) {
    throw new Error('Expected one transaction wrapper: ' + name);
  }
  bodies.push(`-- ${name}\n` + sql.replace(/^begin;\s*/i, '').replace(/\s*commit;$/i, ''));
}

const header = `-- ATHLOS: FIRST INSTALLATION ONLY.
-- Run in the dedicated athlete-monitoring-system Supabase project.
-- Existing installations should apply only their outstanding migrations.
-- Generated by npm run db:bundle; no passwords or API keys are included.
-- One transaction: any error rolls back this installation.

begin;

`;
await writeFile(new URL('install.sql', root), header + bodies.join('\n\n') + '\n\ncommit;\n');
console.log('Prepared supabase/install.sql from ' + names.length + ' migrations.');
